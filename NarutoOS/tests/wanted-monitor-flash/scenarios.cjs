module.exports = async ({ call, wait, until, pass, assert }) => {
  await call('reset', 'confirm');
  await call('entry');
  await call('select');
  await call('execute');
  await call('openWanted', 'ready');
  let state = await until(s => s.yesCount === 1, 4000);
  await wait(250);
  state = await call('state');
  assert.equal(state.stopAICalls, 0, JSON.stringify(state));
  assert.equal(state.nativeStarts, 1, JSON.stringify(state));
  assert.ok(!state.status.includes('无法打开本次通缉的单人确认'), state.status);
  pass('synchronous solo confirmation hide ignores its late loadingEnd callback');
  await call('stop');
  state = await call('state');
  assert.equal(state.stopAICalls, 1, JSON.stringify(state));
  assert.equal(state.stoppedAIType, 'wanted', JSON.stringify(state));
  pass('stopping after accepted confirmation sends native StopAI(WANTED)');

  await call('reset', 'direct');
  await call('entry');
  await call('quiz');
  await call('select');
  await call('execute');
  await call('openWanted', 'ready');
  await wait(300);
  await call('closeWanted');
  await call('left', '1');
  await wait(3600);
  state = await call('state');
  assert.equal(state.quizNav, 0, JSON.stringify(state));
  await call('row', '1');
  await call('left', '0');
  await wait(3600);
  state = await call('state');
  assert.equal(state.quizNav, 0, JSON.stringify(state));
  await call('lock', '1');
  await call('row', '0');
  await wait(3500);
  state = await call('state');
  assert.equal(state.quizNav, 0, JSON.stringify(state));
  await call('lock', '0');
  state = await until(s => s.quizNav === 1, 8000);
  assert.equal(state.quizNav, 1, JSON.stringify(state));
  await wait(1000);
  assert.equal((await call('state')).quizNav, 1);
  pass('quiz selected before wanted waits through gaps, accepted final task, and fight lock; hands off once');

  await call('reset', 'startQueued');
  await call('entry');
  await call('select');
  await call('execute');
  await call('openWanted', 'ready');
  state = await until(s => s.startRequests === 1, 3000);
  assert.equal(state.nativeStarts, 0, JSON.stringify(state));
  await call('stop');
  state = await call('state');
  assert.equal(state.stopAICalls, 0, JSON.stringify(state));
  pass('stopping a queued but unexecuted native command does not stop an unrelated AI');

  await call('reset', 'startQueued');
  await call('entry');
  await call('select');
  await call('execute');
  await call('openWanted', 'ready');
  await until(s => s.startRequests === 1, 3000);
  state = await until(s => s.drawn, 10000);
  assert.equal(state.nativeStarts, 0, JSON.stringify(state));
  assert.equal(state.stopAICalls, 0, JSON.stringify(state));
  pass('unexecuted wanted request times out as ABORT without stopping native AI');

  await call('reset', 'teamCaptain');
  await call('entry');
  await call('select');
  await call('execute');
  state = await call('state');
  assert.equal(state.navCount, 0, JSON.stringify(state));
  assert.equal(state.clicks, 0, JSON.stringify(state));
  pass('team captain is refused before navigation or native wanted activation');

  await call('reset', 'teamCaptain');
  await call('lock', '1');
  await call('entry');
  await call('select');
  await call('execute');
  await call('openWanted', 'ready');
  await call('closeWanted');
  await call('sceneUnknown');
  state = await call('state');
  assert.equal(state.clicks, 0, JSON.stringify(state));
  assert.equal(state.startRequests, 0, JSON.stringify(state));
  await call('lock', '0');
  await wait(1300);
  state = await call('state');
  assert.equal(state.clicks, 0, JSON.stringify(state));
  await call('sceneReady');
  await wait(1300);
  pass('monitoring a team refusal ignores a later wanted NPC dialog');

  for (const uncertainTeamMode of ['teamUnknown', 'teamMembersUnknown']) {
    await call('reset', uncertainTeamMode);
    await call('entry');
    await call('select');
    await call('execute');
    state = await call('state');
    assert.equal(state.navCount, 0, JSON.stringify(state));
    assert.equal(state.clicks, 0, JSON.stringify(state));
  }
  pass('missing team model or unknown joined members fails closed before navigation');

  await call('reset', 'teamAfterNav');
  await call('entry');
  await call('select');
  await call('execute');
  state = await call('state');
  assert.equal(state.navCount, 1, JSON.stringify(state));
  assert.equal(state.clicks, 0, JSON.stringify(state));
  pass('team membership acquired during navigation is monitored before NPC activation');

  await call('reset', 'direct');
  await call('left', '0');
  await call('row', '0');
  await call('openWanted', 'ready');
  await call('entry');
  await call('select');
  await call('execute');
  state = await call('state');
  assert.equal(state.clicks, 0, JSON.stringify(state));
  assert.equal(state.navCount, 0, JSON.stringify(state));
  pass('already completed daily wanted is closed and handed back without starting AI');
  return {};
};
